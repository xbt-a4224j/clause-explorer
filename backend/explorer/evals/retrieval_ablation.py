"""Pure vector vs pure BM25 vs hybrid, over the known-item eval set (#17).

`python -m explorer.evals.retrieval_ablation`

Runs with **no API key** — every query is in the committed embedding cache. Writes
`docs/results/retrieval-ablation.md`.

The rule this file exists under: whatever the numbers say gets written down. If hybrid loses
to pure vector, that is the finding, and alpha does not get tuned until the story improves.
"""

from __future__ import annotations

import time
from dataclasses import dataclass
from pathlib import Path

from explorer.api.logging import configure_logging, get_logger
from explorer.api.settings import settings
from explorer.evals.retrieval_set import EvalQuery, build_eval_set
from explorer.retrieval.hybrid import HybridIndex

RESULTS = Path(__file__).resolve().parents[3] / "docs" / "results" / "retrieval-ablation.md"
ALPHAS = (0.0, 0.3, 0.5, 0.7, 1.0)  # 0.0 is pure BM25, 1.0 is pure vector
K_VALUES = (1, 5, 10)


@dataclass
class Metrics:
    label: str
    recall_at: dict[int, float]
    mrr: float
    n: int


def evaluate(index: HybridIndex, queries: list[EvalQuery], alpha: float, label: str) -> Metrics:
    hits = {k: 0 for k in K_VALUES}
    reciprocal = 0.0
    for item in queries:
        ranked = [s.matter_id for s in index.search(item.query, alpha=alpha, limit=max(K_VALUES))]
        for k in K_VALUES:
            if item.relevant_matter_id in ranked[:k]:
                hits[k] += 1
        if item.relevant_matter_id in ranked:
            reciprocal += 1.0 / (ranked.index(item.relevant_matter_id) + 1)
    total = len(queries)
    return Metrics(
        label=label,
        recall_at={k: hits[k] / total for k in K_VALUES},
        mrr=reciprocal / total,
        n=total,
    )


def run(dsn: str | None = None) -> list[Metrics]:
    log = get_logger().bind(eval="retrieval_ablation")
    started = time.perf_counter()

    queries = build_eval_set(dsn)
    index = HybridIndex.from_postgres(dsn)

    results = [
        evaluate(
            index,
            queries,
            alpha,
            {0.0: "pure BM25", 1.0: "pure vector"}.get(alpha, f"hybrid alpha={alpha}"),
        )
        for alpha in ALPHAS
    ]

    by_template = {
        template: [
            evaluate(index, [q for q in queries if q.template == template], alpha, str(alpha))
            for alpha in (0.0, 0.5, 1.0)
        ]
        for template in sorted({q.template for q in queries})
    }

    _write(results, by_template, len(index.ids))
    log.info(
        "retrieval_ablation_done",
        queries=len(queries),
        corpus=len(index.ids),
        duration_ms=round((time.perf_counter() - started) * 1000, 1),
        best=max(results, key=lambda m: m.mrr).label,
    )
    return results


def _row(metrics: Metrics) -> str:
    cells = " | ".join(f"{metrics.recall_at[k]:.3f}" for k in K_VALUES)
    return f"| {metrics.label} | {cells} | {metrics.mrr:.3f} |"


def _write(results: list[Metrics], by_template: dict[str, list[Metrics]], corpus: int) -> None:
    best = max(results, key=lambda m: m.mrr)
    pure_vector = next(m for m in results if m.label == "pure vector")
    pure_bm25 = next(m for m in results if m.label == "pure BM25")
    hybrids = [m for m in results if m.label.startswith("hybrid")]
    best_hybrid = max(hybrids, key=lambda m: m.mrr)

    verdict = (
        f"**Hybrid wins.** Best is {best_hybrid.label} at MRR {best_hybrid.mrr:.3f}, against "
        f"{pure_vector.mrr:.3f} for pure vector and {pure_bm25.mrr:.3f} for pure BM25."
        if best_hybrid.mrr > max(pure_vector.mrr, pure_bm25.mrr)
        else (
            f"**Hybrid does not win on this eval set.** The best single method is "
            f"{best.label} at MRR {best.mrr:.3f}; the best hybrid is {best_hybrid.label} at "
            f"{best_hybrid.mrr:.3f}. Recorded as measured — alpha has not been tuned to make "
            f"the story look better, and this is the number that should drive whether hybrid "
            f"stays in the retrieval path."
        )
    )

    header = " | ".join(f"recall@{k}" for k in K_VALUES)
    dashes = "|---" * (len(K_VALUES) + 2) + "|"

    lines = [
        "# Retrieval ablation",
        "",
        "Generated by `python -m explorer.evals.retrieval_ablation`, which runs with",
        "`OPENAI_API_KEY` unset — every query is in the committed embedding cache.",
        "",
        f"- Corpus: **{corpus} matter summaries**",
        f"- Eval set: **{results[0].n} known-item queries** over 30 matters, three phrasings each",
        "- Metric: recall@k and MRR against the single correct matter per query",
        "",
        "## What this measures, and what it does not",
        "",
        "Known-item retrieval — can the ranker find one specific deal from a description of it?",
        "Relevance is ground truth from the database, not a judgement someone authored, so the",
        'numbers cannot be nudged. It does **not** measure topical similarity ("deals like this',
        'one"), which would need relevance judgements this corpus does not carry. Comparable-deal',
        "ranking (#18) is the topical case and is not evaluated by this table.",
        "",
        "## Results",
        "",
        f"| method | {header} | MRR |",
        dashes,
        *[_row(m) for m in results],
        "",
        verdict,
        "",
        "## By query phrasing",
        "",
        "The three phrasings differ in how much wording they share with the indexed summary,",
        "which is exactly what separates the two methods: `parties` repeats the company names",
        "verbatim, `paraphrase` avoids them.",
        "",
        "| phrasing | method | " + header + " | MRR |",
        "|---" * (len(K_VALUES) + 3) + "|",
    ]
    saturated = [
        template
        for template, metrics_list in by_template.items()
        if all(m.recall_at[1] >= 0.999 for m in metrics_list)
    ]
    label_for = {"0.0": "pure BM25", "0.5": "hybrid 0.5", "1.0": "pure vector"}
    for template, metrics_list in by_template.items():
        for metrics in metrics_list:
            cells = " | ".join(f"{metrics.recall_at[k]:.3f}" for k in K_VALUES)
            lines.append(
                f"| {template} | {label_for[metrics.label]} | {cells} | {metrics.mrr:.3f} |"
            )

    if saturated:
        names = ", ".join("`" + t + "`" for t in saturated)
        lines += [
            "",
            "## Read the aggregate table with this caveat",
            "",
            (
                f"**{len(saturated)} of {len(by_template)} phrasings are saturated** — every "
                f"method scores 1.000 recall@1 on {names}, because those queries name the "
                "parties and the indexed summary contains those names verbatim. Finding them "
                "is not a hard retrieval task for anything."
            ),
            "",
            (
                "So the aggregate MRR is dominated by a task nothing can fail, and the "
                "differences between methods there are noise. **The discriminating row is "
                "`industry_year`**, where the query shares no proper nouns with the target "
                "summary. That is where the ranking choice actually shows, and it is the row "
                "to look at when deciding whether hybrid earns its place."
            ),
            "",
            (
                "Making the eval harder — queries that describe a deal without naming it — "
                "needs topical relevance judgements this corpus does not carry. Stated rather "
                "than worked around."
            ),
        ]

    RESULTS.parent.mkdir(parents=True, exist_ok=True)
    RESULTS.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    configure_logging(settings.log_level, to_file=False)
    run()


if __name__ == "__main__":
    main()
